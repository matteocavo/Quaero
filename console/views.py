# E. Lineage Viewer
# ---------------------------------------------------------------------------


def render_lineage(client: QuaeroClient, project: str) -> None:
    try:
        lineage = client.lineage(project)
    except NotFoundError as exc:
        st.info(f"Not generated for this project. {exc.detail}")
        return
    except ConsoleError as exc:
        show_error(exc)
        return

    counts = st.columns(2)
    counts[0].metric("Nodes", lineage["node_count"])
    counts[1].metric("Edges", lineage["edge_count"])

    all_types = fmt.lineage_edge_types(lineage)
    chosen = st.multiselect("Edge types", all_types, default=all_types, key="lineage_types")

    if lineage["node_count"] > MAX_GRAPH_NODES:
        st.warning(
            f"The graph has more than {MAX_GRAPH_NODES} nodes and is not drawn; "
            "use the tables below."
        )
    else:
        st.graphviz_chart(fmt.lineage_to_dot(lineage, chosen))

    with st.expander("Nodes"):
        st.dataframe(lineage["nodes"], hide_index=True)
    with st.expander("Edges"):
        edges = [e for e in lineage["edges"] if e["type"] in chosen]
        st.dataframe(edges, hide_index=True)
