def render_quality(client: QuaeroClient, project: str) -> None:
    st.subheader("Data quality")
    try:
        quality = client.data_quality(project)
    except NotFoundError as exc:
        st.info(f"Not generated for this project. {exc.detail}")
    except ConsoleError as exc:
        show_error(exc)
    else:
        for report in quality["reports"]:
            st.markdown(
                f"**Source:** `{report['source']}` · generated {report.get('generated_at')}"
            )
            top = st.columns(2)
            top[0].metric("Overall score", report["overall_score"])
            top[1].metric("Columns scored", report["column_count"])
            flagged = [c["column"] for c in report["columns"] if c["outlier_flag"]]
            st.write(
                "Columns with outlier flag: "
                + (", ".join(f"`{c}`" for c in flagged) if flagged else "none")
            )
            st.dataframe(fmt.dq_columns_to_rows(report), hide_index=True)
        st.caption(
            "Scores come from the pipeline's scorer (completeness, uniqueness, format score; "
            "the outlier flag is informational). The pipeline defines no pass/fail threshold, "
            "so none is shown."
        )

    st.subheader("Anomalies")
    try:
        anomalies = client.anomalies(project)
    except NotFoundError as exc:
        st.info(f"Not generated for this project. {exc.detail}")
    except ConsoleError as exc:
        show_error(exc)
    else:
        st.caption(
            "Framed report (v2): impact, frequency and suggested action."
            if anomalies["version"] == "v2"
            else "Raw detection report (v1): no framing is available for this project."
        )
        if anomalies.get("business_summary"):
            st.info(anomalies["business_summary"])
        st.metric("Rows with anomalies", anomalies["anomaly_row_count"])
        rows = fmt.anomalies_to_rows(anomalies)
        if rows:
            st.dataframe(rows, hide_index=True)
        else:
            st.write("No anomalies were reported.")


