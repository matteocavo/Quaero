"""Streamlit screens of the operations console.

Every function receives an already-configured :class:`QuaeroClient`; no screen touches the
filesystem or the database. Missing artifacts are a normal state ("not generated") and are
never shown as errors; a failing store is shown as unavailable, never as empty data.
"""

from __future__ import annotations

import time
from typing import Any

import pandas as pd
import streamlit as st

from console import formatting as fmt
from console.client import (
    AuthError,
    ConflictError,
    ConsoleError,
    NotFoundError,
    QuaeroClient,
    ServiceUnavailable,
    ValidationRejected,
)

MAX_GRAPH_NODES = 300
PAGE_SIZES = [25, 50, 100, 250]


def show_error(exc: ConsoleError) -> None:
    """Render a console error with wording that matches its meaning."""
    if isinstance(exc, AuthError):
        st.error("The API rejected the API key. Check QUAERO_API_KEY.")
    elif isinstance(exc, ServiceUnavailable):
        st.warning(f"Service unavailable: {exc.detail}")
    elif isinstance(exc, NotFoundError):
        st.info(exc.detail)
    else:
        st.error(exc.detail)


