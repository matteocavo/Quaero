# C. Mart Explorer
# ---------------------------------------------------------------------------


def render_marts(client: QuaeroClient, project: str) -> None:
    try:
        marts = client.list_marts(project)
    except ConsoleError as exc:
        show_error(exc)
        return
    if not marts:
        st.info("This project has no Parquet marts yet.")
        return

    names = [mart["name"] for mart in marts]
    mart = st.selectbox("Mart", names, key="mart_name")
    page_size = st.selectbox("Rows per page", PAGE_SIZES, index=1, key="mart_page_size")
    page = int(st.number_input("Page", min_value=1, value=1, step=1, key="mart_page"))

    try:
        preview = client.mart_preview(project, mart, page=page, page_size=page_size)
    except ConsoleError as exc:
        show_error(exc)
        return

    pages = fmt.total_pages(preview["total_rows"], page_size)
    meta = st.columns(3)
    meta[0].metric("Total rows", preview["total_rows"])
    meta[1].metric("Columns", len(preview["columns"]))
    meta[2].metric("Page", f"{preview['page']} / {pages}")
    with st.expander("Columns"):
        st.write(", ".join(preview["columns"]))

    if page > pages:
        st.warning(f"Page {page} is out of range (last page is {pages}).")
        return

    text = st.text_input(
        "Filter the rows of this page (client-side; the API has no server-side filter)",
        key="mart_filter",
    )
    rows = fmt.filter_rows(preview["rows"], text)
    st.caption(f"Showing {len(rows)} of {len(preview['rows'])} rows on this page.")
    st.dataframe(rows, hide_index=True)
    st.download_button(
        "Download this page (CSV)",
        data=pd.DataFrame(rows, columns=preview["columns"]).to_csv(index=False),
        file_name=f"{project}_{mart}_page{page}.csv",
        mime="text/csv",
        key="mart_csv",
    )


