# A. Project Explorer
# ---------------------------------------------------------------------------


def _overview_row(project: str, overview: dict[str, Any]) -> dict[str, Any]:
    last_run = overview.get("last_run")
    if not overview.get("history_available", True):
        last_status = "history unavailable"
    elif last_run:
        last_status = fmt.status_label(last_run["status"])
    else:
        last_status = "never run"
    artifacts = overview["artifacts"]
    return {
        "project": project,
        "mode": overview.get("project_mode") or "-",
        "marts": overview["marts_count"],
        "last run": last_status,
        "last run at": (last_run or {}).get("created_at"),
        "DQ": artifacts["data_quality"],
        "anomalies": artifacts["anomalies"],
        "lineage": artifacts["lineage"],
    }


def render_explorer(client: QuaeroClient, projects: list[dict[str, Any]], selected: str) -> None:
    if not projects:
        st.info("No projects found under the project root.")
        return

    rows: list[dict[str, Any]] = []
    details: dict[str, dict[str, Any]] = {}
    for item in projects:
        name = item["project"]
        try:
            overview = client.overview(name)
        except ConsoleError as exc:
            rows.append({"project": name, "mode": "-", "last run": f"error: {exc.detail}"})
            continue
        details[name] = overview
        rows.append(_overview_row(name, overview))
    st.dataframe(rows, hide_index=True)

    st.subheader(f"Project: {selected}")
    overview = details.get(selected)
    if overview is None:
        st.warning("The overview of this project could not be loaded.")
        return

    st.write(overview.get("question") or "_No question recorded (no summary report)._")
    left, middle, right = st.columns(3)
    left.metric("Marts", overview["marts_count"])
    middle.metric("Primary mart", overview.get("primary_mart") or "-")
    right.metric("Primary KPI", overview.get("primary_kpi") or "-")

    artifacts = overview["artifacts"]
    st.markdown(
        " · ".join(
            f"{'✅' if present else '➖'} {label}"
            for label, present in (
                ("summary", artifacts["summary"]),
                ("data quality", artifacts["data_quality"]),
                ("anomalies", artifacts["anomalies"]),
                ("lineage", artifacts["lineage"]),
                ("metrics definitions", artifacts["metrics_definitions"]),
            )
        )
    )
    if not (artifacts["data_quality"] and artifacts["lineage"]):
        st.caption(
            "Data quality, lineage and framed anomalies are generated by single-dataset runs only."
        )

    last_run = overview.get("last_run")
    if not overview.get("history_available", True):
        st.warning("Run history is unavailable, so the last run cannot be shown.")
    elif last_run:
        st.write(
            f"Last run: **{fmt.status_label(last_run['status'])}** "
            f"(created {last_run['created_at']}, duration {fmt.run_duration(last_run)})"
        )
        if last_run.get("error"):
            st.error(last_run["error"])
    else:
        st.write("This project has never been run through the API.")


# ---------------------------------------------------------------------------
# B. Pipeline Operations
# ---------------------------------------------------------------------------


def render_operations(
    client: QuaeroClient,
    project: str,
    overview: dict[str, Any] | None,
) -> None:
    flash = st.session_state.pop("flash", None)
    if flash:
        st.success(flash)

    runs: list[dict[str, Any]] = []
    history_ok = True
    try:
        runs = client.run_history(project, limit=50)["runs"]
    except ServiceUnavailable as exc:
        history_ok = False
        st.warning(f"Run history is unavailable: {exc.detail}")
    except NotFoundError:
        runs = []
    except ConsoleError as exc:
        history_ok = False
        show_error(exc)

    active = fmt.latest_active_run(runs)
    has_config = bool(overview and overview.get("has_config"))

    st.subheader("Start a run")
    target = st.text_input("Project", value=project, key="op_project")
    question = st.text_area("Business question", key="op_question", max_chars=1000)
    source_url = st.text_input(
        "Source URL (optional if the project has a project_config.json)", key="op_url"
    )
    if active:
        st.info(
            f"A run is already {active['status']} for this project "
            f"(started {active.get('created_at')}). Wait for it to finish."
        )
    if st.button("Run pipeline", disabled=active is not None, key="op_run"):
        errors = fmt.validate_run_request(
            target, question, source_url, has_config=has_config and target.strip() == project
        )
        if errors:
            for message in errors:
                st.error(message)
        else:
            try:
                accepted = client.start_run(target.strip(), question.strip(), source_url.strip())
            except ConflictError as exc:
                st.warning(f"Not started: {exc.detail}")
            except ValidationRejected as exc:
                st.error(f"The API rejected the request: {exc.detail}")
            except ConsoleError as exc:
                show_error(exc)
            else:
                st.session_state["polls"] = 0
                st.session_state["flash"] = f"Run accepted: {accepted['run_id']}"
                st.rerun()

    st.subheader("Run history")
    controls = st.columns([1, 3])
    controls[0].button("Refresh", key="op_refresh")
    auto = controls[1].checkbox(
        f"Auto-refresh every {fmt.POLL_INTERVAL_SECONDS}s while a run is active "
        f"(stops after {fmt.MAX_POLLS} refreshes)",
        key="op_auto",
    )

    if history_ok:
        if runs:
            st.dataframe(fmt.runs_to_rows(runs), hide_index=True)
        else:
            st.write("No runs recorded for this project.")

    polls = st.session_state.get("polls", 0)
    if auto and active and polls >= fmt.MAX_POLLS:
        st.info("Auto-refresh stopped. Press Refresh to check again.")
    if fmt.should_poll(auto, runs, polls):
        st.session_state["polls"] = polls + 1
        time.sleep(fmt.POLL_INTERVAL_SECONDS)
        st.rerun()
    elif not active:
        st.session_state["polls"] = 0


