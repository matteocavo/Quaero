"""Async run execution with filesystem + SQLite-backed state for Quaero API.

Design notes
------------
* JSON files under ``<project_root>/runs/<run_id>.json`` remain the primary
  source of truth for existing API contracts (backward-compatible).
* SQLite (via ``db.store``) is a secondary, durable record:
  - run history survives restarts and is queryable
  - project registry is auto-populated on first run
  - mart metadata is registered after a successful execution
  The SQLite write is best-effort: a DB failure never fails the API response.
* Only one run per project may be RUNNING at a time.
* ``run_id`` is a UUID4 generated by this module.
* SSRF mitigation: source URLs are validated against a blocklist of private
  and loopback address ranges before the pipeline is invoked.
"""

from __future__ import annotations

import ipaddress
import json
import logging
import os
import socket
import threading
import time
import uuid
from collections.abc import Callable
from pathlib import Path
from typing import Any, TypeVar

from api.schemas import RunStatus
from kpi_engine.question_interpreter import QuestionInterpretationError

LOGGER = logging.getLogger(__name__)
_T = TypeVar("_T")

# ---------------------------------------------------------------------------
# SSRF protection
# ---------------------------------------------------------------------------

_BLOCKED_NETWORKS = [
    ipaddress.ip_network("127.0.0.0/8"),
    ipaddress.ip_network("10.0.0.0/8"),
    ipaddress.ip_network("172.16.0.0/12"),
    ipaddress.ip_network("192.168.0.0/16"),
    ipaddress.ip_network("169.254.0.0/16"),  # link-local / metadata endpoints
    ipaddress.ip_network("::1/128"),
    ipaddress.ip_network("fc00::/7"),
    ipaddress.ip_network("fe80::/10"),
]


def _is_ssrf_risk(url: str) -> bool:
    """Return True if *url* resolves to a private or loopback address."""
    try:
        from urllib.parse import urlparse

        parsed = urlparse(url)
        host = parsed.hostname or ""
        if not host:
            return True
        try:
            addr = ipaddress.ip_address(host)
        except ValueError:
            resolved = socket.getaddrinfo(host, None)
            addrs = [ipaddress.ip_address(r[4][0]) for r in resolved]
        else:
            addrs = [addr]
        for addr in addrs:
            for net in _BLOCKED_NETWORKS:
                if addr in net:
                    return True
        return False
    except Exception:
        return False


# ---------------------------------------------------------------------------
# State helpers (JSON filesystem — primary)
# ---------------------------------------------------------------------------


def _runs_dir(project_root: Path) -> Path:
    """The resolved ``<project_root>/runs`` directory, created if needed."""
    root = os.path.realpath(project_root)
    runs = os.path.realpath(os.path.join(root, "runs"))
    if not runs.startswith(root + os.sep):
        raise ValueError("Runs directory escaped project root.")
    os.makedirs(runs, exist_ok=True)
    return Path(runs)


def _inside_runs_dir(project_root: Path, path: Path) -> Path:
    """*path* resolved, and only if it lies inside the runs directory (checked right before any I/O)."""
    runs = os.path.realpath(_runs_dir(project_root))
    target = os.path.realpath(path)
    if not target.startswith(runs + os.sep):
        raise ValueError(f"not a run file: {path.name}")
    return Path(target)


def _run_path(project_root: Path, run_id: str) -> Path:
    """The run file for *run_id*. Run ids are server-generated UUIDs; anything else is not a run and never
    becomes part of a path."""
    return _inside_runs_dir(
        project_root, _runs_dir(project_root) / f"{uuid.UUID(str(run_id))}.json"
    )


#: On Windows a run file can be refused for a few milliseconds while another thread has it open (a poller
#: reading it, the runner replacing it). That is a temporary sharing conflict: retry with a short, growing pause
#: (about half a second in all), then let the error through. A refusal that lasts is a real problem and must
#: surface, not be retried forever.
_IO_ATTEMPTS = 12
_IO_BACKOFF_STEP_SECONDS = 0.01
_IO_BACKOFF_MAX_SECONDS = 0.05


def _retry_sharing_conflicts(operation: Callable[[], _T]) -> _T:
    for attempt in range(1, _IO_ATTEMPTS + 1):
        try:
            return operation()
        except PermissionError:
            if attempt == _IO_ATTEMPTS:
                raise
            time.sleep(min(_IO_BACKOFF_STEP_SECONDS * attempt, _IO_BACKOFF_MAX_SECONDS))
    raise AssertionError("unreachable")  # pragma: no cover


#: Readers and the writer of this process take turns on run files, so they never meet. The retry above is for
#: whatever the lock cannot see: another process, an antivirus scan, a cloud-sync client.
_RUN_FILE_LOCK = threading.Lock()


def _read_run_file(project_root: Path, path: Path) -> dict[str, Any]:
    target = _inside_runs_dir(project_root, path)

    def read() -> dict[str, Any]:
        with _RUN_FILE_LOCK, target.open(encoding="utf-8") as fh:
            return json.load(fh)

    return _retry_sharing_conflicts(read)


def _existing_run_file(project_root: Path, run_id: str) -> Path | None:
    """The run file whose name is *run_id*, taken from the directory listing: the id is compared with the names
    that exist, never joined into a path, so a request value cannot reach the filesystem."""
    for candidate in _runs_dir(project_root).glob("*.json"):
        if candidate.stem == run_id:
            return candidate
    return None


def _load_run(project_root: Path, run_id: str) -> dict[str, Any] | None:
    path = _existing_run_file(project_root, run_id)
    if path is None:
        return None
    try:
        return _read_run_file(project_root, path)
    except FileNotFoundError:
        return None


def _save_run(project_root: Path, state: dict[str, Any]) -> None:
    """Write the state atomically: a complete file under a unique name, then one replace."""
    path = _inside_runs_dir(project_root, _run_path(project_root, state["run_id"]))
    tmp = _inside_runs_dir(project_root, path.with_name(f"{path.name}.{uuid.uuid4().hex}.tmp"))

    def replace() -> None:
        with _RUN_FILE_LOCK:
            tmp.replace(path)

    try:
        tmp.write_text(json.dumps(state, indent=2), encoding="utf-8")
        _retry_sharing_conflicts(replace)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def _active_run_for_project(project_root: Path, project: str) -> dict[str, Any] | None:
    """Return the first RUNNING or QUEUED run for *project*, or None."""
    runs_dir = _runs_dir(project_root)
    for run_file in runs_dir.glob("*.json"):
        try:
            state = _read_run_file(project_root, run_file)
            if state.get("project") == project and state.get("status") in (
                RunStatus.QUEUED,
                RunStatus.RUNNING,
            ):
                return state
        except Exception:
            continue
    return None


# ---------------------------------------------------------------------------
# SQLite persistence helpers (secondary, best-effort)
# ---------------------------------------------------------------------------


def _db_ensure_project(project_root: Path, project: str) -> None:
    """Register project in SQLite if not already present (best-effort)."""
    try:
        from db import store

        store.register_project(
            name=project,
            root_path=str(project_root / "projects" / project),
        )
    except Exception as exc:
        LOGGER.warning("DB: could not register project %r: %s", project, exc)


def _db_create_run(
    run_id: str,
    project: str,
    question: str | None,
    source_url: str | None,
) -> None:
    try:
        from db import store

        store.create_run(
            run_id=run_id,
            project_name=project,
            question=question,
            source_url=source_url,
        )
    except Exception as exc:
        LOGGER.warning("DB: could not create run %r: %s", run_id, exc)


def _db_transition(
    run_id: str,
    new_status: str,
    error: str | None = None,
    artifact_path: str | None = None,
) -> None:
    try:
        from db import store

        store.transition_run(
            run_id=run_id,
            new_status=new_status,
            error=error,
            artifact_path=artifact_path,
        )
    except Exception as exc:
        LOGGER.warning("DB: could not transition run %r → %r: %s", run_id, new_status, exc)


def _db_register_mart(project_root: Path, project: str, mart_name: str, mart_path: str) -> None:
    try:
        from db import store

        parquet_path = str(project_root / mart_path)
        store.upsert_mart(
            project_name=project,
            mart_name=mart_name,
            parquet_path=parquet_path,
        )
    except Exception as exc:
        LOGGER.warning("DB: could not register mart %r/%r: %s", project, mart_name, exc)


def _db_register_marts(project_root: Path, project: str, result: Any) -> None:
    """Register the Parquet marts listed in ``result["marts"]`` (name -> repo-relative path).

    Only entries whose Parquet file exists on disk are recorded.
    """
    marts = result.get("marts") if isinstance(result, dict) else None
    if not isinstance(marts, dict):
        return
    for mart_name, mart_path in marts.items():
        if (
            isinstance(mart_path, str)
            and mart_path.endswith(".parquet")
            and (project_root / mart_path).is_file()
        ):
            _db_register_mart(project_root, project, mart_name, mart_path)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def create_run(
    project_root: Path,
    project: str,
    question: str | None = None,
    source_url: str | None = None,
) -> dict[str, Any]:
    """Create a new run record (QUEUED) and return its initial state."""
    existing = _active_run_for_project(project_root, project)
    if existing:
        raise RuntimeError(
            f"Project '{project}' already has an active run "
            f"({existing['run_id']}, status={existing['status']}). "
            "Wait for it to complete before submitting another."
        )
    run_id = str(uuid.uuid4())
    state: dict[str, Any] = {
        "run_id": run_id,
        "project": project,
        "status": RunStatus.QUEUED,
        "error": None,
        "result_keys": [],
    }
    _save_run(project_root, state)

    # Persist to SQLite (best-effort, non-blocking)
    _db_ensure_project(project_root, project)
    _db_create_run(run_id, project, question, source_url)

    return state


def get_run(project_root: Path, run_id: str) -> dict[str, Any] | None:
    """Return the run state dict or None if not found."""
    return _load_run(project_root, run_id)


def execute_run(
    project_root: Path,
    run_id: str,
    project: str,
    question: str,
    source_url: str | None,
    metric_column: str | None = None,
    dimension_column: str | None = None,
    aggregation: str | None = None,
) -> None:
    """Execute the pipeline synchronously (called inside a BackgroundTask).

    State transitions: QUEUED → RUNNING → COMPLETED | FAILED
    """
    state = _load_run(project_root, run_id)
    if state is None:
        LOGGER.error("Run %s not found in state store; aborting.", run_id)
        return

    # Transition to RUNNING
    state["status"] = RunStatus.RUNNING
    _save_run(project_root, state)
    _db_transition(run_id, "RUNNING")

    try:
        config_path = project_root / "projects" / project / "project_config.json"
        if config_path.is_file() and source_url is None:
            from app.pipeline_runner import run_project_from_config

            original_config_text: str | None = None
            restore_after_run = False
            try:
                raw_config_text = config_path.read_text(encoding="utf-8")
                parsed_config = json.loads(raw_config_text)
                if isinstance(parsed_config, dict) and parsed_config.get("datasets"):
                    updated = False
                    if (
                        question
                        and question.strip()
                        and parsed_config.get("question") != question.strip()
                    ):
                        parsed_config["question"] = question.strip()
                        updated = True
                    if len(parsed_config["datasets"]) == 1 and isinstance(
                        parsed_config["datasets"][0], dict
                    ):
                        ds0 = parsed_config["datasets"][0]
                        if metric_column is not None:
                            if metric_column.strip():
                                ds0["metric_column"] = metric_column.strip()
                            else:
                                ds0.pop("metric_column", None)
                            updated = True
                        if dimension_column is not None:
                            if dimension_column.strip():
                                ds0["dimension_column"] = dimension_column.strip()
                            else:
                                ds0.pop("dimension_column", None)
                            updated = True
                        if aggregation is not None:
                            ds0["aggregation"] = aggregation
                            updated = True
                    if updated:
                        original_config_text = raw_config_text
                        restore_after_run = "upload_id" not in parsed_config
                        config_path.write_text(
                            json.dumps(parsed_config, indent=2),
                            encoding="utf-8",
                        )
            except Exception:
                original_config_text = None
                restore_after_run = False

            try:
                result = run_project_from_config(
                    config_path=config_path,
                    project_root=project_root,
                )
            finally:
                if restore_after_run and original_config_text is not None:
                    config_path.write_text(original_config_text, encoding="utf-8")
        elif source_url is not None:
            if _is_ssrf_risk(source_url):
                raise ValueError(
                    f"Source URL '{source_url}' resolves to a private or "
                    "loopback address and cannot be used."
                )
            from app.pipeline_runner import run_pipeline as _run_pipeline

            result = _run_pipeline(
                source_path=source_url,
                source_name=project,
                question=question,
                metric_column=(metric_column or "").strip() or None,
                dimension_column=(dimension_column or "").strip() or None,
                aggregation=aggregation,
                project_root=project_root,
            )
        else:
            raise FileNotFoundError(
                f"No project_config.json found for '{project}' and no source_url provided."
            )

        state["status"] = RunStatus.COMPLETED
        result_keys = list(result.keys()) if isinstance(result, dict) else []
        state["result_keys"] = result_keys
        _db_transition(run_id, "COMPLETED")
        _db_register_marts(project_root, project, result)

    except QuestionInterpretationError as exc:
        # An expected outcome, not a crash: the question cannot be answered as asked. The message says why.
        LOGGER.info("Run %s refused the question: %s", run_id, exc)
        state["status"] = RunStatus.FAILED
        state["error"] = str(exc)
        _db_transition(run_id, "FAILED", error=str(exc))

    except Exception as exc:
        LOGGER.exception("Run %s failed: %s", run_id, exc)
        state["status"] = RunStatus.FAILED
        state["error"] = str(exc)
        _db_transition(run_id, "FAILED", error=str(exc))

    _save_run(project_root, state)
